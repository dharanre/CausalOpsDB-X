import json
from datetime import datetime, timezone
from typing import Any
from backend.app.schemas.counterfactual import SimulationRunResponse

class ReportGenerator:
    @staticmethod
    def generate_markdown_audit_report(sim: SimulationRunResponse) -> str:
        md = f"""# CausalOpsDB-X Pre-Deployment Simulation Audit Report
**Simulation ID:** `{sim.simulation_id}`  
**Generated At:** {sim.created_at}  
**Workspace:** `{sim.workspace_id}`  
**Overall Heuristic Risk Score:** **{sim.risk_score:.1f} / 100** (`{sim.risk_category}`)  
**Evidence Coverage:** **{sim.evidence_coverage * 100:.0f}%**  

---

## 1. Executive Summary & Proposed Change
The proposed infrastructure intervention modifies the following resource configuration:
- **Target Resource:** `{sim.intervention.resource_id}`
- **Attribute:** `{sim.intervention.attribute}`
- **Baseline Value:** `{sim.intervention.before_val} {sim.intervention.unit}`
- **Proposed Value:** `{sim.intervention.after_val} {sim.intervention.unit}`
- **Reason:** {sim.intervention.reason}

### Risk Classification: `{sim.risk_category}`
{"CRITICAL WARNING: The simulation detected direct capacity deficit or cascading failures downstream." if sim.risk_score >= 50 else "The proposed change operates within acceptable safety margins."}

---

## 2. Calculated Resource-Level Effects & Mathematical Models
"""
        for idx, effect in enumerate(sim.effects, 1):
            md += f"""### Effect {idx}: {effect.impact_type} (`{effect.severity}`)
- **Affected Resource:** `{effect.resource_id}`
- **Outcome / Value:** `{effect.calculated_value}`
- **Mathematical Formula:** `{effect.formula}`
- **Input Parameters:** `{json.dumps(effect.inputs)}`
- **Assumptions:** {", ".join(effect.assumptions) if effect.assumptions else "Standard operational baseline"}
- **Technical Explanation:** {effect.explanation}

"""

        md += """---

## 3. Downstream Dependency Propagation Path
The following verified dependency chain was traversed by the causal simulation engine:
"""
        for i, res in enumerate(sim.affected_path):
            indent = "  " * i
            arrow = "└── " if i > 0 else "■ "
            md += f"{indent}{arrow}`{res}`\n"

        md += """
---

## 4. Key Recommendations & Countermeasures
"""
        for rec in sim.recommendations:
            md += f"- [ ] {rec}\n"

        md += """
---

*Report generated by CausalOpsDB-X Evidence-Grounded Infrastructure Change Intelligence Engine.*
*All calculations are deterministic, transparent, and grounded in explicit dependency topology and telemetry.*
"""
        return md
